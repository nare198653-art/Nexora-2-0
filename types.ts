export interface AiActionDispatcher {
  createTask: (input: Partial<Task> & { title: string }) => Promise<Task>;
  createTasksBatch: (inputs: Array<Partial<Task> & { title: string }>, idempotencyKey?: string) => Promise<Task[]>;
  updateTask: (taskIdOrTitle: string, updates: Partial<Task>) => Promise<Task | null>;
  deleteTask: (taskIdOrTitle: string) => Promise<boolean>;
  getTasks: (filter?: { status?: 'all' | 'pending' | 'completed'; category?: string; scheduledFor?: string }) => Task[];
  completeTask: (taskIdOrTitle: string) => Promise<Task | null>;
  scheduleTask: (taskIdOrTitle: string, scheduledFor: string, scheduledTime?: string) => Promise<Task | null>;
  rescheduleTask: (taskIdOrTitle: string, scheduledFor: string, scheduledTime?: string) => Promise<Task | null>;
  prioritizeTask: (taskIdOrTitle: string, priority: 'low' | 'medium' | 'high') => Promise<Task | null>;
  getDailyProgress: () => {
    totalTasks: number;
    completedTasks: number;
    pendingTasks: number;
    completionRate: number;
    focusSessionsCompleted: number;
    deepWorkMinutesToday: number;
    streak: number;
    xp: number;
    level: number;
  };
  getWeeklyProgress: () => {
    tasksCompletedThisWeek: number;
    totalTasksTracked: number;
    focusSessionsThisWeek: number;
    deepWorkMinutesThisWeek: number;
    streak: number;
    recentSessions: Array<{ taskTitle?: string; durationMinutes: number; status: string; startedAt: number }>;
  };
  startFocusSession: (opts: { taskId?: string; taskTitle: string; durationMinutes: number; mode?: 'focus' | 'grind' }) => Promise<void>;
  executePendingAction: (action: AiPendingAction) => Promise<AiActionResult>;
}

